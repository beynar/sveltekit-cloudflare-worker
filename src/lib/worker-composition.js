import { createHash } from 'node:crypto';
import { existsSync, readFileSync, statSync } from 'node:fs';
import { builtinModules } from 'node:module';
import path from 'node:path';
import { parse } from 'acorn';

import { KNOWN_HANDLERS } from './dev/constants.js';
import { __sveltekitCloudflareWorkerWaitUntilLast } from './wait-until-last.js';

export const BUILD_ENTRY_MARKER = '// Generated by sveltekit-cloudflare-worker.';

/** Source of the waitUntil.last() helper, inlined into the generated production Worker. */
export const WAIT_UNTIL_LAST_HELPER = __sveltekitCloudflareWorkerWaitUntilLast.toString();

const NODE_BUILTINS = new Set(builtinModules.filter((name) => !name.startsWith('_')));

/**
 * @typedef {{ handlers: string[], classes: string[] }} WorkerExports
 * @typedef {{ path: string, content: string | Uint8Array, hash: string }} BundleFile
 * @typedef {{ files: [BundleFile, ...BundleFile[]], hash: string }} WorkerBundle
 */

/**
 * @typedef {{ find: string | RegExp, replacement: string }} Alias
 * @typedef {{ logLevel?: 'silent' | 'warning', aliases?: readonly Alias[] }} BundleOptions
 */

/** SvelteKit's own aliases point at framework runtime modules that cannot run in a Worker entry. */
const FRAMEWORK_ALIASES = new Set(['$app', '$env', '<sveltekit:generated>', '__sveltekit']);

/**
 * Bundle a user Worker so its public exports can be composed into another Worker entry.
 *
 * Resolution follows the application's Vite setup: `resolve.alias` entries (including SvelteKit
 * `alias` config such as `$lib`), the generated `.svelte-kit/tsconfig.json` paths, package.json
 * `imports` (`#lib/...`) with Vite-style extension lookup, and `node:` built-ins.
 *
 * @param {string} workerPath
 * @param {BundleOptions | 'silent' | 'warning'} [options]
 * @returns {Promise<{ content: string, exports: WorkerExports }>}
 */
export async function bundleWorker(workerPath, options = {}) {
	const { logLevel = 'warning', aliases = [] } =
		typeof options === 'string' ? { logLevel: options } : options;
	const { build } = await import('esbuild');
	const tsconfig = findGeneratedTsconfig(workerPath);
	const result = await build({
		entryPoints: [workerPath],
		write: false,
		metafile: true,
		format: 'esm',
		platform: 'browser',
		target: 'es2024',
		bundle: true,
		external: ['cloudflare:*', 'node:*'],
		conditions: ['workerd', 'worker'],
		resolveExtensions: RESOLVE_EXTENSIONS,
		plugins: [aliasPlugin(aliases), packageImportsPlugin, nodeBuiltinsPlugin],
		...(tsconfig ? { tsconfig } : {}),
		logLevel
	});
	const outputKey = Object.keys(result.metafile.outputs)[0];
	const outputFile = result.outputFiles[0];
	if (!outputKey || !outputFile) {
		throw new Error(`esbuild produced no output for ${workerPath}.`);
	}
	return {
		content: outputFile.text,
		exports: classifyWorkerExports(result.metafile.outputs[outputKey].exports, outputFile.text)
	};
}

const RESOLVE_EXTENSIONS = ['.mts', '.ts', '.tsx', '.mjs', '.js', '.jsx', '.cts', '.cjs', '.json'];

/**
 * @param {readonly Alias[]} aliases
 * @returns {import('esbuild').Plugin}
 */
function aliasPlugin(aliases) {
	const usable = aliases.filter(
		(alias) => typeof alias.find !== 'string' || !FRAMEWORK_ALIASES.has(alias.find)
	);
	return {
		name: 'sveltekit-cloudflare-worker:aliases',
		setup(build) {
			if (usable.length === 0) return;
			build.onResolve({ filter: /.*/ }, async (args) => {
				if (args.pluginData?.aliased || args.path.startsWith('.') || path.isAbsolute(args.path)) {
					return undefined;
				}
				for (const alias of usable) {
					const replaced = applyAlias(alias, args.path);
					if (replaced === undefined) continue;
					return resolveFile(build, replaced, args);
				}
				return undefined;
			});
		}
	};
}

/** @param {Alias} alias @param {string} id */
function applyAlias(alias, id) {
	if (typeof alias.find === 'string') {
		if (id === alias.find) return alias.replacement;
		if (id.startsWith(alias.find + '/')) return alias.replacement + id.slice(alias.find.length);
		return undefined;
	}
	alias.find.lastIndex = 0;
	if (!alias.find.test(id)) return undefined;
	alias.find.lastIndex = 0;
	return id.replace(alias.find, alias.replacement);
}

/**
 * Application package.json `imports` (`#lib`, `#lib/*`) resolved like Vite: the mapped path may
 * omit its extension. Dependencies keep esbuild's standard Node.js semantics.
 * @type {import('esbuild').Plugin}
 */
const packageImportsPlugin = {
	name: 'sveltekit-cloudflare-worker:package-imports',
	setup(build) {
		build.onResolve({ filter: /^#/ }, async (args) => {
			if (args.pluginData?.aliased) return undefined;
			if (args.importer.split(path.sep).includes('node_modules')) return undefined;
			const pkg = findPackageWithImports(args.resolveDir);
			if (!pkg) return undefined;
			const target = matchImports(pkg.imports, args.path);
			if (!target) return undefined;
			if (!target.startsWith('./')) return resolveFile(build, target, args);
			return resolveFile(build, path.resolve(pkg.directory, target), args);
		});
	}
};

/**
 * @param {import('esbuild').PluginBuild} build
 * @param {string} target
 * @param {import('esbuild').OnResolveArgs} args
 */
async function resolveFile(build, target, args) {
	if (path.isAbsolute(target)) {
		const file = findWithExtension(target);
		if (file) return { path: file };
	}
	const result = await build.resolve(target, {
		kind: args.kind,
		importer: args.importer,
		resolveDir: args.resolveDir,
		pluginData: { aliased: true }
	});
	if (result.errors.length > 0) return { errors: result.errors };
	return result;
}

/** @param {string} file */
function findWithExtension(file) {
	if (existsSync(file) && statSync(file).isFile()) return file;
	// TypeScript sources are imported with their emitted extension (`./index.js` -> `./index.ts`).
	const typescript = file.replace(/\.(m|c)?js(x?)$/, (_, kind = '', jsx) => `.${kind}ts${jsx}`);
	if (typescript !== file && existsSync(typescript)) return typescript;
	for (const extension of RESOLVE_EXTENSIONS) {
		if (existsSync(file + extension)) return file + extension;
	}
	for (const extension of RESOLVE_EXTENSIONS) {
		const index = path.join(file, `index${extension}`);
		if (existsSync(index)) return index;
	}
	return undefined;
}

/** @type {Map<string, { directory: string, imports: Record<string, unknown> } | null>} */
const packageImportsCache = new Map();

/** @param {string} directory */
function findPackageWithImports(directory) {
	let current = directory;
	while (true) {
		const cached = packageImportsCache.get(current);
		if (cached !== undefined) return cached;
		const file = path.join(current, 'package.json');
		if (existsSync(file)) {
			let result = null;
			try {
				const json = JSON.parse(readFileSync(file, 'utf-8'));
				if (json.imports && typeof json.imports === 'object') {
					result = { directory: current, imports: json.imports };
				}
			} catch {
				result = null;
			}
			packageImportsCache.set(current, result);
			return result;
		}
		const parent = path.dirname(current);
		if (parent === current) return null;
		current = parent;
	}
}

/** @param {Record<string, unknown>} imports @param {string} specifier */
function matchImports(imports, specifier) {
	if (specifier in imports) return pickCondition(imports[specifier]);
	for (const [key, value] of Object.entries(imports)) {
		const star = key.indexOf('*');
		if (star === -1) continue;
		const prefix = key.slice(0, star);
		const suffix = key.slice(star + 1);
		if (!specifier.startsWith(prefix) || !specifier.endsWith(suffix)) continue;
		const match = specifier.slice(prefix.length, specifier.length - suffix.length);
		const target = pickCondition(value);
		return target?.replaceAll('*', match);
	}
	return undefined;
}

/** @param {unknown} value @returns {string | undefined} */
function pickCondition(value) {
	if (typeof value === 'string') return value;
	if (Array.isArray(value)) {
		for (const item of value) {
			const picked = pickCondition(item);
			if (picked) return picked;
		}
		return undefined;
	}
	if (value && typeof value === 'object') {
		const record = /** @type {Record<string, unknown>} */ (value);
		for (const condition of ['workerd', 'worker', 'import', 'module', 'default']) {
			if (condition in record) {
				const picked = pickCondition(record[condition]);
				if (picked) return picked;
			}
		}
	}
	return undefined;
}

/**
 * With `nodejs_compat`, workerd provides Node built-ins under the `node:` prefix. Rewrite bare
 * specifiers such as `crypto` or `buffer` (common in dependencies) to that prefix and keep them
 * external instead of failing the bundle.
 * @type {import('esbuild').Plugin}
 */
const nodeBuiltinsPlugin = {
	name: 'sveltekit-cloudflare-worker:node-builtins',
	setup(build) {
		build.onResolve({ filter: /^[a-z_][\w./-]*$/ }, (args) => {
			if (!NODE_BUILTINS.has(args.path)) return undefined;
			return { path: `node:${args.path}`, external: true };
		});
	}
};

/**
 * @param {string} workerPath
 * @param {Omit<BundleOptions, 'logLevel'>} [options]
 * @returns {Promise<WorkerExports>}
 */
export async function detectWorkerExports(workerPath, options = {}) {
	return (await bundleWorker(workerPath, { ...options, logLevel: 'silent' })).exports;
}

/**
 * Export names of the Worker entry itself, without bundling its dependencies. Used in
 * development when the full bundle cannot be built (Vite-only syntax, virtual modules...).
 * Every non-handler named export becomes a class candidate; unused class wrappers are inert.
 * @param {string} workerPath
 * @returns {Promise<WorkerExports>}
 */
export async function detectWorkerExportsShallow(workerPath) {
	const { transform } = await import('esbuild');
	const source = readFileSync(workerPath, 'utf-8');
	const { code } = await transform(source, {
		loader: /\.[cm]?tsx?$/.test(workerPath) ? 'ts' : 'js',
		format: 'esm',
		target: 'es2024'
	});
	/** @type {any} */
	const program = parse(code, { ecmaVersion: 'latest', sourceType: 'module' });
	/** @type {string[]} */
	const names = [];
	for (const node of program.body) {
		if (node.type !== 'ExportNamedDeclaration') continue;
		const declaration = node.declaration;
		if (declaration?.id?.name) names.push(declaration.id.name);
		for (const item of declaration?.declarations ?? []) {
			if (item.id?.name) names.push(item.id.name);
		}
		for (const specifier of node.specifiers ?? []) {
			const exported = specifier.exported?.name ?? specifier.exported?.value;
			if (exported) names.push(exported);
		}
	}
	const handlers = names.filter((name) => KNOWN_HANDLERS.includes(name));
	const classes = names.filter(
		(name) => !KNOWN_HANDLERS.includes(name) && name !== 'default' && /^[A-Z]/.test(name)
	);
	return { handlers, classes };
}

/** @param {string[]} exportNames @param {string} bundledSource @returns {WorkerExports} */
export function classifyWorkerExports(exportNames, bundledSource) {
	const handlers = [];
	const classExports = findClassExports(bundledSource);
	const classes = [];
	for (const name of exportNames) {
		if (name === 'default') continue;
		if (KNOWN_HANDLERS.includes(name)) handlers.push(name);
		else if (classExports.has(name)) classes.push(name);
	}
	return { handlers, classes };
}

/** @param {string} source */
function findClassExports(source) {
	const program = /** @type {{ body: unknown[] }} */ (
		/** @type {unknown} */ (parse(source, { ecmaVersion: 'latest', sourceType: 'module' }))
	);
	const classBindings = new Set();
	/** @type {Array<{ local: string, exported: string }>} */
	const exports = [];

	for (const statementValue of program.body) {
		const statement = toRecord(statementValue);
		if (statement.type === 'ClassDeclaration') {
			const name = identifierName(statement.id);
			if (name) classBindings.add(name);
			continue;
		}
		if (statement.type === 'VariableDeclaration') {
			for (const declarationValue of toArray(statement.declarations)) {
				const declaration = toRecord(declarationValue);
				if (toRecord(declaration.init).type !== 'ClassExpression') continue;
				const name = identifierName(declaration.id);
				if (name) classBindings.add(name);
			}
			continue;
		}
		if (statement.type !== 'ExportNamedDeclaration') continue;
		for (const specifierValue of toArray(statement.specifiers)) {
			const specifier = toRecord(specifierValue);
			if (specifier.type !== 'ExportSpecifier') continue;
			const local = identifierName(specifier.local);
			const exported = identifierName(specifier.exported);
			if (local && exported) exports.push({ local, exported });
		}
	}

	return new Set(
		exports.filter(({ local }) => classBindings.has(local)).map(({ exported }) => exported)
	);
}

/** @param {unknown} value */
function identifierName(value) {
	const node = toRecord(value);
	return node.type === 'Identifier' && typeof node.name === 'string' ? node.name : undefined;
}

/** @param {unknown} value @returns {Record<string, unknown>} */
function toRecord(value) {
	return value && typeof value === 'object' && !Array.isArray(value)
		? /** @type {Record<string, unknown>} */ (value)
		: {};
}

/** @param {unknown} value @returns {unknown[]} */
function toArray(value) {
	return Array.isArray(value) ? value : [];
}

/**
 * @param {WorkerExports} exports
 * @param {{ svelteKitImport?: string, userWorkerImport?: string }} [options]
 */
export function createWorkerFacade(exports, options = {}) {
	const svelteKitImport = options.svelteKitImport ?? './_sveltekit-worker.js';
	const userWorkerImport = options.userWorkerImport ?? './_user-worker.js';
	return (
		`${BUILD_ENTRY_MARKER}\n` +
		`import worker_default from ${quoteImport(svelteKitImport)};\n` +
		`import * as __userWorker from ${quoteImport(userWorkerImport)};\n` +
		buildExportBlock(exports, userWorkerImport)
	);
}

/**
 * Compose an in-memory SvelteKit bundle and a user Worker without creating another Worker.
 * The original entry path remains first so callers can keep using it as the main module.
 *
 * @param {WorkerBundle} bundle
 * @param {string} workerPath
 * @returns {Promise<{ bundle: WorkerBundle, exports: WorkerExports }>}
 */
export async function composeWorkerBundle(bundle, workerPath) {
	const userWorker = await bundleWorker(workerPath);
	if (userWorker.exports.handlers.length === 0 && userWorker.exports.classes.length === 0) {
		return { bundle, exports: userWorker.exports };
	}

	const [entry, ...remainingFiles] = bundle.files;
	const entryDirectory = path.posix.dirname(entry.path);
	const svelteKitPath = path.posix.join(entryDirectory, '_sveltekit-worker.js');
	const userWorkerPath = path.posix.join(entryDirectory, '_user-worker.js');
	const reservedPaths = new Set([svelteKitPath, userWorkerPath]);
	const collision = remainingFiles.find((file) => reservedPaths.has(file.path));
	if (collision) {
		throw new Error(`Cannot compose Worker bundle because ${collision.path} already exists.`);
	}

	const facade = createWorkerFacade(userWorker.exports);
	const files = /** @type {[BundleFile, ...BundleFile[]]} */ ([
		{ path: entry.path, content: facade, hash: hashContent(facade) },
		{ path: svelteKitPath, content: entry.content, hash: entry.hash },
		{ path: userWorkerPath, content: userWorker.content, hash: hashContent(userWorker.content) },
		...remainingFiles
	]);
	return {
		bundle: { files, hash: hashBundleFiles(files) },
		exports: userWorker.exports
	};
}

/** @param {WorkerExports} exports @param {string} userWorkerImport */
function buildExportBlock(exports, userWorkerImport) {
	const lines = exports.classes.map(
		(className) => `export { ${className} } from ${quoteImport(userWorkerImport)};`
	);
	const hasFetch = exports.handlers.includes('fetch');
	const otherHandlers = exports.handlers.filter((handler) => handler !== 'fetch');
	const needsWaitUntilLast = hasFetch || otherHandlers.length > 0;
	const defaultEntries = [];

	if (hasFetch) {
		defaultEntries.push(
			`  async fetch(request, env, ctx) {\n` +
				`    const __waitUntilLast = __sveltekitCloudflareWorkerWaitUntilLast(ctx);\n` +
				`    try {\n` +
				`      let nextResponse;\n` +
				`      const next = () => { nextResponse ??= worker_default.fetch(request, env, __waitUntilLast.ctx); return nextResponse; };\n` +
				`      const response = await __userWorker.fetch(request, env, __waitUntilLast.ctx, next);\n` +
				`      if (response) return response;\n` +
				`      return await (nextResponse ?? next());\n` +
				`    } finally {\n` +
				`      __waitUntilLast.flush();\n` +
				`    }\n` +
				`  }`
		);
	} else {
		defaultEntries.push('  fetch: worker_default.fetch');
	}

	for (const handler of otherHandlers) {
		defaultEntries.push(buildHandlerEntry(handler));
	}
	if (needsWaitUntilLast) lines.push(`${WAIT_UNTIL_LAST_HELPER}\n`);
	lines.push(`export default {\n${defaultEntries.join(',\n')}\n};`);
	return lines.join('\n') + '\n';
}

/** @param {string} handler */
function buildHandlerEntry(handler) {
	const firstArg = getHandlerArgument(handler);
	return (
		`  async ${handler}(${firstArg}, env, ctx) {\n` +
		`    const __waitUntilLast = __sveltekitCloudflareWorkerWaitUntilLast(ctx);\n` +
		`    try {\n` +
		`      return await __userWorker.${handler}(${firstArg}, env, __waitUntilLast.ctx);\n` +
		`    } finally {\n` +
		`      __waitUntilLast.flush();\n` +
		`    }\n` +
		`  }`
	);
}

/** @param {string} handler */
function getHandlerArgument(handler) {
	return {
		connect: 'socket',
		scheduled: 'controller',
		queue: 'batch',
		email: 'message',
		tail: 'events',
		trace: 'traces',
		tailStream: 'event',
		test: 'controller'
	}[handler];
}

/** @param {string} workerPath */
function findGeneratedTsconfig(workerPath) {
	let directory = path.dirname(workerPath);
	while (true) {
		const candidate = path.join(directory, '.svelte-kit', 'tsconfig.json');
		if (existsSync(candidate)) return candidate;

		const parent = path.dirname(directory);
		if (parent === directory) return undefined;
		directory = parent;
	}
}

/** @param {string | Uint8Array} content */
function hashContent(content) {
	return createHash('sha256').update(content).digest('hex');
}

/** @param {BundleFile[]} files */
function hashBundleFiles(files) {
	return hashContent(JSON.stringify(files.map((file) => `${file.path}:${file.hash}`)));
}

/** @param {string} specifier */
function quoteImport(specifier) {
	return `'${specifier.replace(/\\/g, '\\\\').replace(/'/g, "\\'")}'`;
}
