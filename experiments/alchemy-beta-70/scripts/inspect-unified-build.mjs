import * as NodeServices from '@effect/platform-node/NodeServices';
import * as Effect from 'effect/Effect';
import sourceModule from 'sveltekit-cloudflare-worker/alchemy-source';

const provider = await Effect.runPromise(
	sourceModule.make({ rootDir: '.', workerFile: 'src/counter-worker.ts' })
);
const output = await Effect.runPromise(
	provider
		.build({
			id: 'UnifiedWebsite',
			workerName: 'alchemy-beta70-unified-worker',
			compatibility: { date: '2026-07-11', flags: ['nodejs_compat'] },
			stack: { name: 'AlchemyBeta70SvelteKitDurableObject', stage: 'dev' },
			env: undefined,
			assets: { directory: '.', runWorkerFirst: true }
		})
		.pipe(Effect.provide(NodeServices.layer))
);

if (!output.bundle) {
	throw new Error('The provider produced no Worker bundle.');
}

const entry = output.bundle.files[0];
const entrySource =
	typeof entry.content === 'string' ? entry.content : new TextDecoder().decode(entry.content);
const checks = {
	mainModuleIsFacade: entrySource.startsWith('// Generated by sveltekit-cloudflare-worker.'),
	hasDefaultHandler: entrySource.includes('export default {'),
	hasCounterExport: entrySource.includes("export { Counter } from './_user-worker.js';"),
	hasFetchMiddleware: entrySource.includes('await __userWorker.fetch('),
	hasSvelteKitModule: output.bundle.files.some((file) =>
		file.path.endsWith('_sveltekit-worker.js')
	),
	hasUserWorkerModule: output.bundle.files.some((file) => file.path.endsWith('_user-worker.js'))
};

if (Object.values(checks).includes(false)) {
	throw new Error(`Unified Worker bundle check failed: ${JSON.stringify(checks)}`);
}

console.log(
	JSON.stringify(
		{
			question: 'Does the Alchemy source produce one deployable Worker with SvelteKit and Counter?',
			answer: 'yes',
			mainModule: entry.path,
			moduleCount: output.bundle.files.length,
			assetCount: Object.keys(output.assets?.manifest ?? {}).length,
			checks
		},
		null,
		2
	)
);
